/**
 * lore-reel.js — the story of a page's Lore Archive, told as a framed slideshow of card art.
 *
 * Markup, in the Lore Archive after its quote: the story itself, one <li> per
 * slide in the same order as the slides in lore-reel-data.js.
 *   <div class="lore-reel" data-lore-reel="artmage" data-pcs-scope="lore-reel"
 *        data-suggest-context="Lore Archive: story slideshow">
 *     <ol class="lore-reel-story" data-pcs-skip>
 *       <li>At the heart of the Artmages' artistic magic stands the <strong>Acropolis</strong> academy.</li>
 *       …
 *     </ol>
 *   </div>
 * Without script the list is simply the story in text.
 *
 * A page loads three scripts, all deferred and in this order: lore-reel-data.js,
 * lore-reel-art.js (generated by scripts/build_lore_art.py; rerun it after adding
 * cards to the data, or those cards fall back to the slower CardLoader lookup), lore-reel.js.
 *
 * Slides come from LoreReelData[<key>] (lore-reel-data.js), with '|' between two
 * acts of the story (a wider gap between their pips). Each slide is a card's
 * cropped art in a pixel frame, drifting from one height of the art to another,
 * with its <li> as the caption underneath. The change to the next is a mosaic:
 * the art breaks into ever larger blocks and resolves into the next one, and the
 * caption crossfades at the peak. The caption box is as tall as the longest
 * caption, so the page doesn't jump (on phones it fits each caption instead).
 * "Read the whole story" shows every <li> at once and pauses the slideshow;
 * clicking a passage there brings up its art. Clicking the art opens the usual
 * card popup.
 *
 * "Who's who" (the reel's cast in lore-reel-data.js): one portrait per person,
 * showing the card they are at the current chapter, so it's plain that
 * Diactorus, Vidolium and Mediclius are all Medius. The people named in the
 * current passage are lit; a portrait opens its card's popup.
 *
 * Holds still while offscreen, while the art is hovered, on keyboard focus, and with its pause
 * button. Under prefers-reduced-motion it starts paused, doesn't drift, and cuts
 * between slides. Art is fetched a slide ahead, once the reel is near the viewport.
 * Only draws the art (never reads it back), so any art URL works.
 *
 * Rosters (kind: 'roster' in lore-reel-data.js), for pages whose official lore is
 * profiles rather than a story: an optional intro, then one <li> per person in
 * the data's order, with a <p data-form="j"> for anything that only applies to
 * their j-th card.
 *   <div class="lore-reel" data-lore-reel="k9" data-pcs-scope="lore-roster"
 *        data-suggest-context="Lore Archive: roster">
 *     <p class="lore-roster-intro">…</p>
 *     <ol class="lore-roster-list" data-pcs-skip>
 *       <li><p>One of the new squadron's commanders, <strong>Izuna</strong> …</p>
 *           <p data-form="1">Released, Izuna is registered as <strong>Ripper</strong> …</p></li>
 *     </ol>
 *   </div>
 * The portraits (grouped by each person's `group`) pick whose art is in the
 * frame; a person with several cards gets a button per card. Nothing plays by
 * itself: the art drifts once and rests.
 *
 * Art trails (kind: 'trail') are rosters of artworks, for pages with no official
 * story or profiles: `stops` in lore-reel-data.js, one <li> note per stop in the
 * same <ol class="lore-roster-list">, with previous/next buttons. A card named in
 * a note as <span data-card="Exact Card Name">…</span> walks to its stop, or
 * opens the card's popup when it isn't on the trail.
 *   <div class="lore-reel" data-lore-reel="dragonmaid" data-pcs-scope="lore-trail"
 *        data-suggest-context="Lore Archive: art trail"> … </div>
 *
 * Music: every reel has a speaker. The first press loads lore-music-data.js and
 * lore-music.js from beside this file (nothing is downloaded before that), and
 * the choice is remembered: a reader who left the music on hears it again when
 * a reel comes into view, if the browser allows sound without a click (as Chrome
 * and Edge do after a click on the previous page of the site), or else at their
 * first click or key press. This file tells lore-music.js what happens,
 * with events on the reel's root (and the last chapter as root.loreReelChapter):
 *   lore-reel:change   { to }        a change has started (the mosaic)
 *   lore-reel:chapter  { kind, index, from, count, color, actStart, paused,
 *                        people: [{ name, el, lit, changed }] }
 *   lore-reel:state    { paused }
 * A new reel needs a palette in lore-music-data.js, or it plays the fantasy one.
 *
 * Renders on DOMContentLoaded, before the pages' own initPageSections() call,
 * so page-sections.js finds the controls and adds its suggestion link.
 */
(function () {
    'use strict';

    // lore-music.js and its data sit beside this file
    const SCRIPT_BASE = ((document.currentScript && document.currentScript.src) || '../assets/js/lore-reel.js').replace(/[^/]*$/, '');

    const HOLD_MS = 7500;
    const CHANGE_MS = 900;
    // Block size in CSS px for each step of a change; the slide swaps at the peak.
    const MOSAIC = [3, 6, 12, 24, 48, 48, 24, 12, 6, 3];
    const FRAME_INSET = 18;    // the frame's padding, both sides

    // Background position (percent) that puts art point f (0-1) in the middle of a portrait zoomed by z.
    const focusPos = (f, z) => Math.max(0, Math.min(100, (f * z - 0.5) / (z - 1) * 100));
    const escapeRegExp = text => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const DEFAULT_ZOOM = 2.4;

    const toRoman = n => [[10, 'X'], [9, 'IX'], [5, 'V'], [4, 'IV'], [1, 'I']]
        .reduce((out, [value, glyph]) => { while (n >= value) { out += glyph; n -= value; } return out; }, '');

    const reduceMotion = !!(window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches);

    // 5:2 like the page banners; 5:3 on phones, where a 5:2 strip would be under 100px tall.
    const aspectFor = width => width < 480 ? 0.6 : 0.4;
    const easeInOut = x => 0.5 - Math.cos(Math.PI * Math.max(0, Math.min(1, x))) / 2;

    // Pixel glyphs drawn on a small grid, so they stay as crisp as the frame.
    const pixelIcon = (w, h, rects) =>
        `<svg viewBox="0 0 ${w} ${h}" width="${w * 2}" height="${h * 2}" shape-rendering="crispEdges" aria-hidden="true">` +
        rects.map(([x, y, rw, rh]) => `<rect x="${x}" y="${y}" width="${rw}" height="${rh}"/>`).join('') + '</svg>';
    const ICONS = {
        prev: pixelIcon(8, 7, [[4, 0, 2, 1], [3, 1, 2, 1], [2, 2, 2, 1], [1, 3, 2, 1], [2, 4, 2, 1], [3, 5, 2, 1], [4, 6, 2, 1]]),
        next: pixelIcon(8, 7, [[2, 0, 2, 1], [3, 1, 2, 1], [4, 2, 2, 1], [5, 3, 2, 1], [4, 4, 2, 1], [3, 5, 2, 1], [2, 6, 2, 1]]),
        play: pixelIcon(7, 7, [[2, 0, 1, 7], [3, 1, 1, 5], [4, 2, 1, 3], [5, 3, 1, 1]]),
        pause: pixelIcon(7, 7, [[1, 0, 2, 7], [4, 0, 2, 7]]),
        lines: pixelIcon(7, 7, [[0, 0, 7, 1], [0, 3, 7, 1], [0, 6, 4, 1]]),
        frame: pixelIcon(7, 7, [[0, 0, 7, 1], [0, 6, 7, 1], [0, 1, 1, 5], [6, 1, 1, 5], [2, 2, 3, 3]]),
        // A speaker, with sound waves while the music is on and a cross while it's off (lore-reel.css)
        sound: '<svg viewBox="0 0 10 7" width="20" height="14" shape-rendering="crispEdges" aria-hidden="true">'
            + '<rect x="0" y="2" width="2" height="3"/><rect x="2" y="1" width="1" height="5"/><rect x="3" y="0" width="1" height="7"/>'
            + '<g class="lore-reel-sound-waves"><rect x="5" y="2" width="1" height="3"/><g class="lore-reel-sound-far">'
            + '<rect x="7" y="1" width="1" height="1"/><rect x="8" y="2" width="1" height="3"/><rect x="7" y="5" width="1" height="1"/></g></g>'
            + '<g class="lore-reel-sound-off"><rect x="6" y="2" width="1" height="1"/><rect x="9" y="2" width="1" height="1"/>'
            + '<rect x="7" y="3" width="2" height="1"/><rect x="6" y="4" width="1" height="1"/><rect x="9" y="4" width="1" height="1"/></g></svg>'
    };

    // The reel's content width: a page may give it padding of its own (Melffy's dark panel).
    function innerWidth(node) {
        const style = getComputedStyle(node);
        return node.clientWidth - (parseFloat(style.paddingLeft) || 0) - (parseFloat(style.paddingRight) || 0);
    }

    // A portrait tab's name (Who's who, roster, trail). A one-word name slightly too wide for its tab
    // (Eliminator) gets up to a fifth smaller rather than breaking mid-word. A longer one
    // (Phospheroglacier) keeps its size and hyphenates: the browser has no dictionary for invented
    // names, so give those a soft hyphen in the data ('Phosphero­glacier'). A name with hyphens
    // or soft hyphens (Hide-and-seek) can already break after each one, so its parts are measured.
    function fitName(tab) {
        const name = tab.querySelector('.lore-reel-person-name');
        if (!name) return;
        name.style.fontSize = '';
        const room = innerWidth(tab);
        if (room <= 0) return;
        const probe = name.cloneNode(false);
        probe.style.cssText = 'position: absolute; visibility: hidden; white-space: nowrap; max-width: none';
        tab.append(probe);
        const widest = Math.max(...name.textContent.split(/\s+|(?<=[-­])/).map(word => {
            probe.textContent = word;
            return probe.getBoundingClientRect().width;
        }));
        probe.remove();
        if (widest <= room) return;
        const size = parseFloat(getComputedStyle(name).fontSize);
        const fit = Math.floor(size * room / widest * 10) / 10;
        if (fit >= size * 0.8) name.style.fontSize = fit + 'px';
    }

    function el(tag, className, text) {
        const node = document.createElement(tag);
        if (className) node.className = className;
        if (text) node.textContent = text;
        return node;
    }

    function controlButton(className, icon, label) {
        const button = el('button', className);
        button.type = 'button';
        button.innerHTML = icon;
        button.setAttribute('aria-label', label);
        return button;
    }

    function openCard(cardName, event) {
        if (window.CardLoader && typeof CardLoader.showPopupByName === 'function') {
            CardLoader.showPopupByName(cardName, event);
        }
    }

    // ---- Music ----
    // lore-music.js is loaded on the first press of a speaker, never before.
    const MUSIC_PREF = 'loreMusic';
    let musicLoad = null;

    const musicWanted = () => {
        try { return localStorage.getItem(MUSIC_PREF) === 'on'; } catch (e) { return false; }
    };

    function loadMusic() {
        if (!musicLoad) {
            const add = src => new Promise((resolve, reject) => {
                const script = document.createElement('script');
                script.src = SCRIPT_BASE + src;
                script.onload = resolve;
                script.onerror = () => reject(new Error(`${src} did not load`));
                document.head.append(script);
            });
            musicLoad = add('lore-music-data.js').then(() => add('lore-music.js')).then(() => window.LoreMusic)
                .catch(error => { musicLoad = null; console.warn('[LoreReel] No music:', error.message); return null; });
        }
        return musicLoad;
    }

    // Some browsers only allow sound that starts in a click, so the audio context is made here,
    // in the click, and lore-music.js picks it up once it has loaded.
    function unlockAudio() {
        const Ctx = window.AudioContext || window.webkitAudioContext;
        if (!Ctx) return;
        if (!window.LoreReelAudio) window.LoreReelAudio = new Ctx();
        if (window.LoreReelAudio.state === 'suspended') window.LoreReelAudio.resume().catch(() => {});
    }

    function setMusic(on, root) {
        if (on) unlockAudio();
        loadMusic().then(music => { if (music) music.setOn(on, root); });
    }

    function soundButton(root) {
        const button = controlButton('lore-reel-btn lore-reel-sound', ICONS.sound, 'Play music');
        button.setAttribute('aria-pressed', String(musicWanted()));
        button.addEventListener('click', () => setMusic(button.getAttribute('aria-pressed') !== 'true', root));
        return button;
    }

    // Tells lore-music.js what the reel is doing; the last chapter stays on the root for when it loads later
    function emit(root, type, detail) {
        if (type === 'chapter') root.loreReelChapter = detail;
        root.dispatchEvent(new CustomEvent(`lore-reel:${type}`, { detail, bubbles: true }));
    }

    // Whether this page may play sound without a click. Asked once: a new audio context only starts
    // running if so (Chrome and Edge allow it after a click on the previous page of the site, and any
    // browser does for a site its settings allow). Firefox can say so directly.
    let soundCheck = null;
    function soundAllowed() {
        if (!soundCheck) {
            const Ctx = window.AudioContext || window.webkitAudioContext;
            if (!Ctx) soundCheck = Promise.resolve(false);
            else if (navigator.getAutoplayPolicy) soundCheck = Promise.resolve(navigator.getAutoplayPolicy('audiocontext') === 'allowed');
            else {
                if (!window.LoreReelAudio) window.LoreReelAudio = new Ctx();
                const ctx = window.LoreReelAudio;
                soundCheck = ctx.state === 'running' ? Promise.resolve(true) : Promise.race([
                    ctx.resume().then(() => ctx.state === 'running'),
                    new Promise(resolve => setTimeout(() => resolve(false), 500))   // blocked: resume() never settles
                ]);
            }
        }
        return soundCheck;
    }

    // A reader who left the music on hears it again as soon as the browser allows: when a reel comes into
    // view if sound may play without a click, otherwise at their first click or key press on the page.
    // Until then the reel's instruments load, so the music starts without a wait. A speaker handles itself.
    function resumeMusic() {
        if (!musicWanted()) return;
        const roots = [...document.querySelectorAll('[data-lore-reel-ready]')];
        let done = false, observer = null;
        const finish = () => {
            done = true;
            if (observer) observer.disconnect();
            ['pointerdown', 'keydown'].forEach(type => document.removeEventListener(type, onGesture, true));
        };
        const start = root => {
            if (done) return;
            finish();
            setMusic(true, root);
        };
        const onGesture = event => {
            if (event.target.closest && event.target.closest('.lore-reel-sound')) finish();
            else start(roots.find(root => root.loreReelInView) || roots[0]);
        };
        ['pointerdown', 'keydown'].forEach(type => document.addEventListener(type, onGesture, true));
        if (!('IntersectionObserver' in window)) return;
        observer = new IntersectionObserver(entries => {
            entries.forEach(entry => { entry.target.loreReelInView = entry.isIntersecting; });
            const seen = entries.find(entry => entry.isIntersecting);
            if (!seen || done) return;
            soundAllowed().then(allowed => {
                if (allowed) start(seen.target);
                else loadMusic().then(music => { if (music && !done) music.prepare(seen.target); });
            });
        });
        roots.forEach(root => observer.observe(root));
    }

    function loadImage(url, urgent) {
        return new Promise(resolve => {
            const img = new Image();
            img.decoding = 'async';
            if (urgent) img.fetchPriority = 'high';
            // Decoded before it's handed over, so the first draw doesn't stall the animation.
            img.onload = () => (img.decode ? img.decode().catch(() => {}) : Promise.resolve()).then(() => resolve(img));
            img.onerror = () => resolve(null);
            img.src = url;
        });
    }

    // ---- Art ----
    // Slides and portraits use the pre-sized WebPs listed in lore-reel-art.js (built by
    // scripts/build_lore_art.py): <base>art/<id>.webp at 624px and <base>face/<id>.webp at 256px,
    // straight from the bucket, with no card lookup first. A card missing there, or a file that
    // fails, falls back to CardLoader's lookup and the full cropped image.
    // Every reel on the page shares one queue of at most MAX_LOADS downloads, and the art on
    // screen jumps it, so the first slide isn't splitting the connection with a dozen portraits.
    const MAX_LOADS = 3;
    const loads = new Map();   // 'art|Card Name' or 'face|Card Name' -> { job, promise }
    const waiting = [];
    let running = 0;

    function manifestUrl(card, size) {
        const manifest = window.LoreReelArt, id = manifest && manifest.ids && manifest.ids[card];
        return id ? `${manifest.base}${size}/${id}.webp` : null;
    }

    async function fetchImage(card, size, urgent) {
        const direct = manifestUrl(card, size);
        const img = direct && await loadImage(direct, urgent);
        if (img) return img;
        if (!window.CardLoader || typeof CardLoader.getCardCroppedImageUrl !== 'function') return null;
        const url = await CardLoader.getCardCroppedImageUrl(card);
        return url ? loadImage(url, urgent) : null;
    }

    function pump() {
        while (running < MAX_LOADS && waiting.length) {
            const job = waiting.shift();
            running++;
            fetchImage(job.card, job.size, job.urgent)
                .catch(() => null)
                .then(img => {
                    running--;
                    job.resolve(img);
                    pump();
                });
        }
    }

    // One promise per card and size; asking again with urgent moves a queued download to the front.
    function loadArt(card, size, urgent) {
        const key = `${size}|${card}`;
        let entry = loads.get(key);
        if (!entry) {
            const job = { card, size, urgent: false };
            entry = { job, promise: new Promise(resolve => { job.resolve = resolve; }) };
            loads.set(key, entry);
            waiting.push(job);
        }
        if (urgent && !entry.job.urgent) {
            entry.job.urgent = true;
            const at = waiting.indexOf(entry.job);
            if (at > 0) waiting.unshift(...waiting.splice(at, 1));
        }
        pump();
        return entry.promise;
    }

    // Cover the canvas with the art, its band centred on height fy (0-1) where the art allows.
    function paintSlide(canvas, img, fy) {
        const ctx = canvas.getContext('2d'), W = canvas.width, H = canvas.height;
        ctx.fillStyle = '#0f0b18';
        ctx.fillRect(0, 0, W, H);
        if (!img) return;
        const scale = Math.max(W / img.naturalWidth, H / img.naturalHeight);
        const dw = img.naturalWidth * scale, dh = img.naturalHeight * scale;
        const top = Math.max(0, Math.min(dh - H, fy * dh - H / 2));
        ctx.imageSmoothingEnabled = true;
        ctx.imageSmoothingQuality = 'high';
        ctx.drawImage(img, (W - dw) / 2, -top, dw, dh);
    }

    // Shrink the slide to one pixel per block, then blow it back up unsmoothed.
    function mosaic(ctx, src, small, block) {
        const sw = Math.ceil(src.width / block), sh = Math.ceil(src.height / block);
        small.width = sw;
        small.height = sh;
        const sctx = small.getContext('2d');
        sctx.imageSmoothingEnabled = true;
        sctx.imageSmoothingQuality = 'high';
        sctx.drawImage(src, 0, 0, sw, sh);
        ctx.imageSmoothingEnabled = false;
        ctx.drawImage(small, 0, 0, sw * block, sh * block);
        ctx.imageSmoothingEnabled = true;
    }

    function render(root) {
        if (root.dataset.loreReelReady) return;
        const reel = window.LoreReelData && window.LoreReelData[root.dataset.loreReel];
        if (!reel || !reel.slides || !reel.slides.length) {
            console.warn('[LoreReel] No slides for', root.dataset.loreReel);
            return;
        }
        root.dataset.loreReelReady = 'true';
        const slides = reel.slides.filter(item => item !== '|'), count = slides.length;
        // Slide indices that open a new act
        const actStarts = new Set();
        reel.slides.forEach((item, j) => { if (item === '|') actStarts.add(j - actStarts.size); });
        const story = root.querySelector('.lore-reel-story');
        const captions = story ? [...story.children] : [];
        if (story && captions.length !== count) {
            console.warn(`[LoreReel] ${root.dataset.loreReel}: ${captions.length} story lines for ${count} slides`);
        }

        root.setAttribute('role', 'region');
        root.setAttribute('aria-roledescription', 'carousel');
        root.setAttribute('aria-label', reel.label || 'The story in card art');

        // ---- DOM ----
        const frame = el('figure', 'lore-reel-frame');
        const artButton = el('button', 'lore-reel-art');
        artButton.type = 'button';
        const canvas = el('canvas');
        canvas.setAttribute('role', 'img');
        artButton.append(canvas);
        const plaque = el('figcaption', 'lore-reel-plaque');
        frame.append(artButton, plaque);

        const chapter = el('div', 'lore-reel-chapter');
        chapter.setAttribute('aria-live', 'off');
        const prev = controlButton('lore-reel-btn', ICONS.prev, 'Previous chapter');
        const next = controlButton('lore-reel-btn', ICONS.next, 'Next chapter');
        const play = controlButton('lore-reel-btn', '', '');
        const pipRow = el('div', 'lore-reel-pips');
        const pips = slides.map((slide, k) => {
            if (actStarts.has(k)) pipRow.append(el('span', 'lore-reel-act-gap'));
            const pip = el('button', 'lore-reel-pip');
            pip.type = 'button';
            pip.style.setProperty('--beat', slide.color);
            pip.setAttribute('aria-label', `Chapter ${toRoman(k + 1)}: ${slide.title}`);
            pip.append(el('i'));
            pip.addEventListener('click', () => go(k, true));
            pipRow.append(pip);
            return pip;
        });
        // A long story gets narrower pips, so the chapter label keeps its room.
        if (count > 14) root.style.setProperty('--pip-w', '15px');
        const sound = soundButton(root);
        const controls = el('div', 'lore-reel-ctrl');
        controls.append(prev, pipRow, next, play, sound);
        const bar = el('div', 'lore-reel-bar');
        bar.append(chapter, controls);
        root.prepend(frame, bar);

        // The story list becomes the caption under the art, with a switch to read it whole.
        let toggle = null;
        if (story) {
            story.id = story.id || `lore-reel-story-${root.dataset.loreReel}`;
            story.classList.add('is-captions');
            story.setAttribute('aria-live', 'off');
            captions.forEach((line, k) => {
                if (k >= count) return;
                line.dataset.numeral = toRoman(k + 1);
                line.style.setProperty('--beat', slides[k].color);
                line.classList.toggle('is-act-start', actStarts.has(k));
            });
            toggle = el('button', 'lore-reel-toggle');
            toggle.type = 'button';
            toggle.setAttribute('aria-controls', story.id);
            story.after(toggle);
        }

        // Who's who: one portrait per person, in the form they have at the current chapter.
        const people = (reel.cast || []).map(person => {
            const button = el('button', 'lore-reel-person');
            button.type = 'button';
            if (person.color) button.style.setProperty('--ring', person.color);
            const face = el('span', 'lore-reel-face');
            face.setAttribute('aria-hidden', 'true');
            const as = el('span', 'lore-reel-person-as');
            button.append(face, el('span', 'lore-reel-person-name', person.name), as);
            const names = (person.names || [person.name]).map(escapeRegExp).join('|');
            return {
                person, button, face, as, form: null,
                forms: person.forms.slice().sort((a, b) => a.from - b.from),
                named: new RegExp(`\\b(?:${names})\\b`)
            };
        });
        if (people.length) {
            const castBox = el('div', 'lore-reel-cast');
            castBox.setAttribute('role', 'group');
            castBox.setAttribute('aria-label', "Who's who");
            const row = el('div', 'lore-reel-cast-row');
            row.append(...people.map(entry => entry.button));
            castBox.append(el('div', 'lore-reel-cast-label', "Who's who"), row);
            (toggle || story || bar).after(castBox);
        }

        // ---- State ----
        const st = {
            i: 0, t: 0,        // slide on screen, ms into its hold
            next: -1, p: 0,    // slide being changed to, and how far along (0-1)
            shown: -1,         // slide the labels describe; they swap halfway through a change
            userPaused: reduceMotion, hover: false, visible: false, cw: 0, dpr: 1,
            full: false, pausedBeforeFull: false   // "Read the whole story" is open; the play state it replaced
        };
        const art = slides.map(() => null), requested = new Set();
        const faceUrls = new Map(), facesRequested = new Set();
        const buffer = el('canvas'), small = el('canvas');
        let loaded = 0, nearView = false, pipSteps = 8, lastKey = '', pausedShown = null, frameId = 0, last = 0;

        const panAt = (k, t) => {
            const [from, to] = slides[k].pan || [0.5, 0.5];
            return reduceMotion ? to : from + (to - from) * easeInOut(t / HOLD_MS);
        };

        function draw() {
            if (!st.cw) return;
            const fy = panAt(st.i, st.t);
            const step = st.next < 0 ? -1 : Math.min(MOSAIC.length - 1, Math.floor(st.p * MOSAIC.length));
            const key = [st.i, st.next, step, fy.toFixed(4), loaded, canvas.width].join('|');
            if (key === lastKey) return;   // nothing on screen would change
            lastKey = key;
            if (step < 0) {
                paintSlide(canvas, art[st.i], fy);
            } else if (step < MOSAIC.length / 2) {
                paintSlide(buffer, art[st.i], fy);
                mosaic(canvas.getContext('2d'), buffer, small, Math.max(1, Math.round(MOSAIC[step] * st.dpr)));
            } else {
                paintSlide(buffer, art[st.next], panAt(st.next, 0));
                mosaic(canvas.getContext('2d'), buffer, small, Math.max(1, Math.round(MOSAIC[step] * st.dpr)));
            }
        }

        // Where the label shares a row with the controls, it keeps room for its longest title,
        // so no title is cut and the pips don't shift between chapters. If that room and pips
        // of at least 9px can't share the row, the bar stacks as it does on phones.
        const probe = el('div', 'lore-reel-chapter');
        probe.setAttribute('aria-hidden', 'true');
        probe.style.cssText = 'position: absolute; visibility: hidden; pointer-events: none; left: 0; top: 0;';
        bar.append(probe);
        const actGaps = pipRow.querySelectorAll('.lore-reel-act-gap').length;
        function fitBar() {
            let widest = 0;
            slides.forEach((slide, k) => {
                const label = el('span');
                label.append(el('span', 'lore-reel-num', toRoman(k + 1)), ` · ${slide.title}`);
                probe.replaceChildren(label);
                widest = Math.max(widest, probe.getBoundingClientRect().width);
            });
            probe.replaceChildren();
            root.classList.remove('is-stacked');
            chapter.style.minWidth = '';
            const barStyle = getComputedStyle(bar);
            if (barStyle.flexDirection !== 'row') return;   // phones: the label has a row of its own
            const px = value => parseFloat(value) || 0;
            const ctrlStyle = getComputedStyle(controls), pipStyle = getComputedStyle(pipRow);
            const controlsMin = prev.offsetWidth + next.offsetWidth + play.offsetWidth + sound.offsetWidth + 4 * px(ctrlStyle.columnGap)
                + count * 9 + actGaps * 6 + (count + actGaps - 1) * px(pipStyle.columnGap)
                + px(pipStyle.paddingLeft) + px(pipStyle.paddingRight);
            if (widest + px(barStyle.columnGap) + controlsMin > bar.clientWidth) root.classList.add('is-stacked');
            else chapter.style.minWidth = Math.ceil(widest) + 'px';
        }

        function labelBeat(k) {
            if (st.shown === k) return;
            const from = st.shown;
            st.shown = k;
            const slide = slides[k], numeral = toRoman(k + 1);
            root.style.setProperty('--beat', slide.color);
            plaque.textContent = slide.card;
            const label = el('span');
            label.append(el('span', 'lore-reel-num', numeral), ` · ${slide.title}`);
            chapter.replaceChildren(label);
            artButton.setAttribute('aria-label', `Show card: ${slide.card}`);
            canvas.setAttribute('aria-label', `Chapter ${numeral}, ${slide.title}. Art from ${slide.card}.`);
            pips.forEach((pip, j) => j === k ? pip.setAttribute('aria-current', 'step') : pip.removeAttribute('aria-current'));
            captions.forEach((line, j) => line.classList.toggle('is-on', j === k));

            // Who's who: each person's form at this chapter, lit if the passage names them.
            const passage = captions[k] ? captions[k].textContent.replace(/\s+/g, ' ') : '';
            const cast = people.map(entry => {
                const form = formAt(entry, k);
                const on = slides[k].on;   // a slide can name who's on stage when its passage names no one
                const lit = on ? on.includes(entry.person.name) : !captions[k] || entry.named.test(passage);
                entry.button.classList.toggle('is-lit', lit);
                const changed = form !== entry.form && entry.form !== null;
                if (form !== entry.form) {
                    entry.form = form;
                    showForm(entry, changed);
                }
                entry.button.setAttribute('aria-label',
                    `${entry.person.name}${form.as ? `, as ${form.card}` : ''}${lit ? ', in this chapter' : ''}. Show card`);
                fetchFace(formAt(entry, (k + 1) % count).card);
                return { name: entry.person.name, el: entry.button, lit, changed };
            });
            emit(root, 'chapter', { kind: 'story', index: k, from, count, color: slide.color, actStart: actStarts.has(k), paused: st.userPaused, people: cast });
        }

        function formAt(entry, k) {
            let form = entry.forms[0];
            entry.forms.forEach(candidate => { if (candidate.from <= k) form = candidate; });
            return form;
        }

        function showForm(entry, animate) {
            const { form, face } = entry, zoom = form.zoom || DEFAULT_ZOOM, [fx, fy] = form.face || [0.5, 0.3];
            face.style.backgroundSize = `${zoom * 100}%`;
            face.style.backgroundPosition = `${focusPos(fx, zoom)}% ${focusPos(fy, zoom)}%`;
            const url = faceUrls.get(form.card);
            face.style.backgroundImage = url ? `url("${url}")` : '';
            if (!url) fetchFace(form.card);
            entry.as.textContent = form.as ? `as ${form.as}` : '';
            if (animate && !reduceMotion) {   // a short pixel "pop" when someone changes card
                entry.button.classList.remove('is-changing');
                void entry.button.offsetWidth;
                entry.button.classList.add('is-changing');
            }
        }

        // A portrait's art, fetched once it's near the viewport, and shown once it has loaded.
        function fetchFace(card) {
            if (!nearView || facesRequested.has(card)) return;
            facesRequested.add(card);
            loadArt(card, 'face').then(img => {
                if (!img) return;
                faceUrls.set(card, img.src);
                people.forEach(entry => {
                    if (entry.form && entry.form.card === card) entry.face.style.backgroundImage = `url("${img.src}")`;
                });
            });
        }

        function sync() {
            const current = st.next >= 0 ? (st.shown === st.next ? 0 : 1)
                : Math.floor(st.t / HOLD_MS * pipSteps) / pipSteps;
            pips.forEach((pip, j) => pip.style.setProperty('--fill', j < st.shown ? 1 : j > st.shown ? 0 : current));
            if (st.userPaused === pausedShown) return;
            pausedShown = st.userPaused;
            play.innerHTML = st.userPaused ? ICONS.play : ICONS.pause;
            play.setAttribute('aria-label', st.userPaused ? 'Play slideshow' : 'Pause slideshow');
            emit(root, 'state', { paused: st.userPaused });   // the music thins out while the slideshow is paused
        }

        const animating = () => st.next >= 0 || (!st.userPaused && !st.hover);

        function wake() {
            if (frameId || !st.visible) return;
            last = 0;
            frameId = requestAnimationFrame(tick);
        }

        function tick(now) {
            frameId = 0;
            const dt = last ? Math.min(100, now - last) : 0;
            last = now;
            if (!st.visible || !st.cw) return;
            if (st.next >= 0) {
                st.p += dt / CHANGE_MS;
                if (st.p >= 0.5) labelBeat(st.next);
                if (st.p >= 1) {
                    st.i = st.next;
                    st.next = -1;
                    st.t = 0;
                }
            } else if (!st.userPaused && !st.hover && art[st.i]) {   // the clock waits for the art
                st.t = Math.min(HOLD_MS, st.t + dt);
                if (st.t >= HOLD_MS) go(st.i + 1, false);
            }
            draw();
            sync();
            if (!frameId && st.visible && animating()) frameId = requestAnimationFrame(tick);
        }

        function go(k, manual) {
            k = (k + count) % count;
            fetchArt(k, true);
            fetchArt(k + 1);
            if (st.next >= 0) {   // finish a change that is still running
                st.i = st.next;
                st.next = -1;
                labelBeat(st.i);
            }
            // Announce only what the reader asked for
            [chapter, story].forEach(node => node && node.setAttribute('aria-live', manual ? 'polite' : 'off'));
            if (k === st.i) {
                st.t = 0;
            } else if (reduceMotion || !st.visible) {
                st.i = k;
                st.t = 0;
                labelBeat(k);
            } else {
                st.next = k;
                st.p = 0;
                emit(root, 'change', { to: k });
            }
            draw();
            sync();
            wake();
        }

        function layout() {
            people.forEach(entry => fitName(entry.button));
            const cw = Math.floor((innerWidth(root) - FRAME_INSET) / 3) * 3;   // whole 3px steps, like the frame bands
            if (cw <= 0) return;
            fitBar();
            pipSteps = Math.max(1, Math.round(pips[0].offsetWidth / 3));   // pips fill in 3px steps
            const ch = Math.round(cw * aspectFor(cw) / 3) * 3, dpr = window.devicePixelRatio || 1;
            if (cw === st.cw && dpr === st.dpr) return;
            st.cw = cw;
            st.dpr = dpr;
            canvas.style.width = cw + 'px';
            canvas.style.height = ch + 'px';
            [canvas, buffer].forEach(c => {
                c.width = Math.round(cw * dpr);
                c.height = Math.round(ch * dpr);
            });
            lastKey = '';
            draw();
        }

        // The art for slide k, fetched once and only after the reel has come near the viewport.
        // urgent: it's the slide going on screen, so it jumps the download queue.
        function fetchArt(k, urgent) {
            k = (k + count) % count;
            if (!nearView || (requested.has(k) && !urgent)) return;
            requested.add(k);
            loadArt(slides[k].card, 'art', urgent).then(img => {
                if (!img || art[k]) return;
                art[k] = img;
                loaded++;
                draw();
            });
        }

        // In order of need: the art on screen, the portraits, then the next slide and its portraits.
        function comeNear() {
            nearView = true;
            fetchArt(st.i, true);
            people.forEach(entry => fetchFace(entry.form.card));
            fetchArt(st.i + 1);
            people.forEach(entry => fetchFace(formAt(entry, (st.shown + 1) % count).card));
        }

        // ---- Events ----
        prev.addEventListener('click', () => go(st.shown - 1, true));
        next.addEventListener('click', () => go(st.shown + 1, true));
        play.addEventListener('click', () => {
            st.userPaused = !st.userPaused;
            sync();
            wake();
        });
        artButton.addEventListener('click', event => openCard(slides[st.shown].card, event));
        people.forEach(entry => {
            entry.button.addEventListener('click', event => openCard(entry.form.card, event));
            entry.button.addEventListener('animationend', () => entry.button.classList.remove('is-changing'));
        });
        root.addEventListener('keydown', event => {
            if (event.key !== 'ArrowLeft' && event.key !== 'ArrowRight') return;
            event.preventDefault();
            go(st.shown + (event.key === 'ArrowRight' ? 1 : -1), true);
        });

        // Hovering the art, or keyboard focus anywhere in the reel, holds the current
        // beat. A mouse click leaves focus on a button, so only :focus-visible counts.
        frame.addEventListener('pointerenter', event => {
            if (event.pointerType === 'mouse') st.hover = true;
        });
        frame.addEventListener('pointerleave', () => {
            st.hover = false;
            wake();
        });
        root.addEventListener('focusin', event => {
            if (event.target.matches(':focus-visible')) st.hover = true;
        });
        root.addEventListener('focusout', event => {
            if (root.contains(event.relatedTarget)) return;
            st.hover = false;
            wake();
        });

        function setFull(on) {
            if (on !== st.full) {
                st.full = on;
                if (on) {
                    st.pausedBeforeFull = st.userPaused;
                    st.userPaused = true;
                } else {
                    st.userPaused = st.pausedBeforeFull;
                }
            }
            // Switch modes without the captions' crossfade, which would briefly stack every passage.
            story.classList.add('is-switching');
            story.classList.toggle('is-full', on);
            story.classList.toggle('is-captions', !on);
            void story.offsetWidth;
            story.classList.remove('is-switching');
            toggle.setAttribute('aria-expanded', String(on));
            toggle.innerHTML = on ? `${ICONS.frame}<span>One chapter at a time</span>` : `${ICONS.lines}<span>Read the whole story</span>`;
            sync();
            wake();
        }

        if (story) {
            toggle.addEventListener('click', () => {
                setFull(!st.full);
                // Folding the whole story back up can leave the art above the screen: bring it back.
                if (!st.full && root.getBoundingClientRect().top < 0) {
                    root.scrollIntoView({ block: 'start', behavior: reduceMotion ? 'auto' : 'smooth' });
                }
            });
            captions.forEach((line, k) => line.addEventListener('click', event => {
                // In the whole story, a passage brings up its art. Links and buttons keep
                // their own click, and selecting text isn't a jump.
                if (!st.full || k >= count) return;
                if (event.target.closest('a, button')) return;
                const selection = window.getSelection && window.getSelection();
                if (selection && !selection.isCollapsed) return;
                go(k, true);
            }));
            setFull(false);
        }

        labelBeat(0);
        sync();
        layout();

        if ('ResizeObserver' in window) new ResizeObserver(layout).observe(root);
        else window.addEventListener('resize', layout);
        // Titles are measured in the page font, which may still be loading.
        if (document.fonts && document.fonts.ready) document.fonts.ready.then(layout);

        if ('IntersectionObserver' in window) {
            new IntersectionObserver(([entry]) => {
                st.visible = entry.isIntersecting;
                lastKey = '';
                if (!st.visible && st.next >= 0) {   // the art left the screen mid-change: finish it now
                    st.i = st.next;
                    st.next = -1;
                    st.t = 0;
                    labelBeat(st.i);
                    sync();
                }
                if (st.visible) {
                    draw();
                    wake();
                }
            }).observe(canvas);
            const artObserver = new IntersectionObserver(entries => {
                if (!entries.some(entry => entry.isIntersecting)) return;
                artObserver.disconnect();
                comeNear();
            }, { rootMargin: '300px' });
            artObserver.observe(root);
        } else {
            st.visible = true;
            comeNear();
            wake();
        }
    }

    // ---------------------------------------------------------------- Roster
    // For a page whose official lore is profiles rather than a story (kind: 'roster').
    // Portraits to pick from, the chosen card's art in the same frame, and that
    // person's profile under it. Nothing plays by itself: the art drifts once and
    // rests, and a new pick comes in through the same mosaic.
    const DRIFT_MS = 9000;

    function renderRoster(root, roster) {
        if (root.dataset.loreReelReady) return;
        // An art trail is a roster of card artworks: one card per stop, walked in order.
        const trail = roster.kind === 'trail';
        const people = trail
            ? (roster.stops || []).map(stop => ({
                name: stop.title, color: stop.color,
                forms: [{ card: stop.card, face: stop.face, pan: stop.pan, zoom: stop.zoom }]
            }))
            : roster.people || [];
        if (!people.length) {
            console.warn('[LoreReel] Nothing to show for', root.dataset.loreReel);
            return;
        }
        root.dataset.loreReelReady = 'true';
        root.classList.add('lore-roster');
        if (trail) root.classList.add('lore-trail');
        const key = root.dataset.loreReel;
        const list = root.querySelector('.lore-roster-list');
        const items = list ? [...list.children] : [];
        if (list && items.length !== people.length) {
            console.warn(`[LoreReel] ${key}: ${items.length} profiles for ${people.length} people`);
        }
        root.setAttribute('role', 'region');
        root.setAttribute('aria-label', roster.label || 'Who is who');

        // Each person's pickable cards, flattened: view v is card j of person k.
        const views = [];
        people.forEach((person, k) => person.forms.forEach((form, j) => views.push({ k, j, form })));
        const viewOf = (k, j) => views.findIndex(view => view.k === k && view.j === j);
        const picked = people.map(() => 0);   // the card each person was last shown in

        // ---- DOM ----
        const strip = el('div', 'lore-roster-strip');
        strip.setAttribute('role', 'group');
        strip.setAttribute('aria-label', roster.label || 'Who is who');
        let row = null, groupName;
        const tabs = people.map((person, k) => {
            if (!row || person.group !== groupName) {
                groupName = person.group;
                const group = el('div', 'lore-roster-group');
                if (person.group) group.append(el('div', 'lore-roster-group-label', person.group));
                row = el('div', 'lore-roster-group-row');
                group.append(row);
                strip.append(group);
            }
            const tab = el('button', 'lore-reel-person lore-roster-tab');
            tab.type = 'button';
            if (person.color) tab.style.setProperty('--ring', person.color);
            const face = el('span', 'lore-reel-face');
            face.setAttribute('aria-hidden', 'true');
            tab.append(face, el('span', 'lore-reel-person-name', person.name));
            tab.setAttribute('aria-label', person.tag ? `${person.name}, ${person.tag}` : person.name);
            tab.addEventListener('click', () => select(viewOf(k, picked[k]), true));
            row.append(tab);
            return { tab, face };
        });

        const frame = el('figure', 'lore-reel-frame');
        const artButton = el('button', 'lore-reel-art');
        artButton.type = 'button';
        const canvas = el('canvas');
        canvas.setAttribute('role', 'img');
        artButton.append(canvas);
        const plaque = el('figcaption', 'lore-reel-plaque');
        frame.append(artButton, plaque);

        const head = el('div', 'lore-roster-head');
        const nameLine = el('div', 'lore-roster-name');
        const formRow = el('div', 'lore-roster-forms');
        formRow.setAttribute('role', 'group');
        head.append(nameLine);
        // The row of card buttons keeps its place even for one-card people, so the page doesn't move.
        if (people.some(person => person.forms.length > 1)) head.append(formRow);
        const stepTo = d => select(viewOf((views[st.shown].k + d + people.length) % people.length, 0), true);
        const counter = el('span', 'lore-trail-count');
        const sound = soundButton(root);
        if (trail) {
            const prevStop = controlButton('lore-reel-btn', ICONS.prev, 'Previous stop');
            const nextStop = controlButton('lore-reel-btn', ICONS.next, 'Next stop');
            prevStop.addEventListener('click', () => stepTo(-1));
            nextStop.addEventListener('click', () => stepTo(1));
            const nav = el('div', 'lore-trail-nav');
            nav.append(prevStop, counter, nextStop, sound);
            head.append(nav);
        } else {
            head.append(sound);
        }

        if (list) {
            list.id = list.id || `lore-roster-list-${key}`;
            list.classList.add('is-captions');
            list.setAttribute('aria-live', 'off');
            // A person's notes on their other cards share one cell, the height of the longest.
            items.forEach(item => {
                const notes = [...item.querySelectorAll(':scope > p[data-form]')];
                if (!notes.length) return;
                const box = el('div', 'lore-roster-notes');
                box.append(...notes);
                item.append(box);
            });
            list.before(strip, frame, head);
        } else {
            root.append(strip, frame, head);
        }

        // ---- State ----
        const st = { v: 0, next: -1, p: 0, t: 0, shown: -1, visible: false, cw: 0, dpr: 1 };
        const art = new Map(), requested = new Set(), faceUrls = new Map(), facesRequested = new Set();
        const buffer = el('canvas'), small = el('canvas');
        let nearView = false, lastKey = '', frameId = 0, last = 0, loaded = 0;

        const panAt = (v, t) => {
            const [from, to] = views[v].form.pan || [0.45, 0.25];
            return reduceMotion ? to : from + (to - from) * easeInOut(t / DRIFT_MS);
        };

        function draw() {
            if (!st.cw) return;
            const fy = panAt(st.v, st.t);
            const step = st.next < 0 ? -1 : Math.min(MOSAIC.length - 1, Math.floor(st.p * MOSAIC.length));
            const drawKey = [st.v, st.next, step, fy.toFixed(4), loaded, canvas.width].join('|');
            if (drawKey === lastKey) return;
            lastKey = drawKey;
            const img = v => art.get(views[v].form.card) || null;
            if (step < 0) {
                paintSlide(canvas, img(st.v), fy);
            } else if (step < MOSAIC.length / 2) {
                paintSlide(buffer, img(st.v), fy);
                mosaic(canvas.getContext('2d'), buffer, small, Math.max(1, Math.round(MOSAIC[step] * st.dpr)));
            } else {
                paintSlide(buffer, img(st.next), panAt(st.next, 0));
                mosaic(canvas.getContext('2d'), buffer, small, Math.max(1, Math.round(MOSAIC[step] * st.dpr)));
            }
        }

        // A portrait shows the card last picked, if the extra cards are the person's forms;
        // with portraits: 'first' (extra cards are scenes, like Mikanko's dances) it keeps the first.
        const portraitOf = k => people[k].forms[roster.portraits === 'first' ? 0 : picked[k]];

        function setFace(k) {
            const form = portraitOf(k), face = tabs[k].face;
            const zoom = form.zoom || DEFAULT_ZOOM, [fx, fy] = form.face || [0.5, 0.3];
            face.style.backgroundSize = `${zoom * 100}%`;
            face.style.backgroundPosition = `${focusPos(fx, zoom)}% ${focusPos(fy, zoom)}%`;
            const url = faceUrls.get(form.card);
            face.style.backgroundImage = url ? `url("${url}")` : '';
            if (!url) fetchFace(form.card);
        }

        // What the labels, profile and portraits say, for view v; swapped halfway through a change.
        function show(v) {
            if (st.shown === v) return;
            const from = st.shown, before = st.shown >= 0 ? views[st.shown] : null;
            st.shown = v;
            const { k, j, form } = views[v], person = people[k];
            picked[k] = j;
            root.style.setProperty('--beat', person.color || 'var(--reel-ink)');
            plaque.textContent = form.card;
            artButton.setAttribute('aria-label', `Show card: ${form.card}`);
            canvas.setAttribute('aria-label', `${person.name}${form.as ? `, as ${form.as}` : ''}. Art from ${form.card}.`);
            const name = el('span');
            if (trail) name.append(el('span', 'lore-reel-num', toRoman(k + 1)), ' · ');
            if (person.tag) name.append(el('span', 'lore-roster-tag', person.tag), ' ');
            name.append(person.name);
            nameLine.replaceChildren(name);
            counter.textContent = `${k + 1} / ${people.length}`;
            tabs[k].tab.classList.add('is-visited');

            if (!before || before.k !== k) {
                formRow.replaceChildren();
                formRow.setAttribute('aria-label', `${person.name}: cards`);
                if (person.forms.length > 1) {
                    person.forms.forEach((option, jj) => {
                        const button = el('button', 'lore-roster-form', option.as || person.name);
                        button.type = 'button';
                        button.addEventListener('click', () => select(viewOf(k, jj), true));
                        formRow.append(button);
                    });
                }
            }
            [...formRow.children].forEach((button, jj) => button.setAttribute('aria-pressed', String(jj === j)));
            tabs.forEach(({ tab }, kk) => tab.setAttribute('aria-pressed', String(kk === k)));
            setFace(k);
            if (before && before.k === k && before.j !== j && !reduceMotion) {   // the same pixel "pop" as a form change in Who's who
                tabs[k].tab.classList.remove('is-changing');
                void tabs[k].tab.offsetWidth;
                tabs[k].tab.classList.add('is-changing');
            }
            items.forEach((item, kk) => {
                item.classList.toggle('is-on', kk === k);
                item.querySelectorAll('p[data-form]').forEach(note => note.classList.toggle('is-on', kk === k && +note.dataset.form === j));
            });
            prefetch(k);
            emit(root, 'chapter', {
                kind: trail ? 'trail' : 'roster', index: v, from, count: views.length, color: person.color, actStart: false, paused: false,
                people: [{ name: person.name, el: tabs[k].tab, lit: true, changed: !!(before && before.k === k && before.j !== j) }]
            });
        }

        // The rest of a person's cards, and the next person's, come in ahead of time.
        function prefetch(k) {
            people[k].forms.forEach(option => fetchArt(option.card));
            fetchArt(people[(k + 1) % people.length].forms[0].card);
        }

        function wake() {
            if (frameId || !st.visible) return;
            last = 0;
            frameId = requestAnimationFrame(tick);
        }

        function tick(now) {
            frameId = 0;
            const dt = last ? Math.min(100, now - last) : 0;
            last = now;
            if (!st.visible || !st.cw) return;
            if (st.next >= 0) {
                st.p += dt / CHANGE_MS;
                if (st.p >= 0.5) show(st.next);
                if (st.p >= 1) {
                    st.v = st.next;
                    st.next = -1;
                    st.t = 0;
                }
            } else if (art.get(views[st.v].form.card)) {   // the drift waits for the art
                st.t = Math.min(DRIFT_MS, st.t + dt);
            }
            draw();
            if (st.visible && (st.next >= 0 || (!reduceMotion && st.t < DRIFT_MS))) frameId = requestAnimationFrame(tick);
        }

        function select(v, manual) {
            if (v < 0) return;
            fetchArt(views[v].form.card, true);
            if (st.next >= 0) {   // finish a change that is still running
                st.v = st.next;
                st.next = -1;
                show(st.v);
            }
            if (list) list.setAttribute('aria-live', manual ? 'polite' : 'off');
            if (v === st.v) return;
            if (reduceMotion || !st.visible) {
                st.v = v;
                st.t = 0;
                show(v);
            } else {
                st.next = v;
                st.p = 0;
                emit(root, 'change', { to: v });
            }
            draw();
            wake();
        }

        function fitNames() {
            tabs.forEach(({ tab }) => fitName(tab));
        }

        function layout() {
            fitNames();
            const cw = Math.floor((innerWidth(root) - FRAME_INSET) / 3) * 3;
            if (cw <= 0) return;
            const ch = Math.round(cw * aspectFor(cw) / 3) * 3, dpr = window.devicePixelRatio || 1;
            if (cw === st.cw && dpr === st.dpr) return;
            st.cw = cw;
            st.dpr = dpr;
            canvas.style.width = cw + 'px';
            canvas.style.height = ch + 'px';
            [canvas, buffer].forEach(c => {
                c.width = Math.round(cw * dpr);
                c.height = Math.round(ch * dpr);
            });
            lastKey = '';
            draw();
        }

        // urgent: the card going into the frame, so it jumps the download queue.
        function fetchArt(card, urgent) {
            if (!nearView || (requested.has(card) && !urgent)) return;
            requested.add(card);
            loadArt(card, 'art', urgent).then(img => {
                if (!img || art.has(card)) return;
                art.set(card, img);
                loaded++;
                draw();
                wake();
            });
        }

        // Portraits have their own small file (256px), not a crop of the full art.
        function fetchFace(card) {
            if (!nearView || facesRequested.has(card) || faceUrls.has(card)) return;
            facesRequested.add(card);
            loadArt(card, 'face').then(img => {
                if (!img) return;
                faceUrls.set(card, img.src);
                tabs.forEach((_, k) => { if (portraitOf(k).card === card) setFace(k); });
            });
        }

        // In order of need: the art in the frame, the portraits, then what's likely next.
        function comeNear() {
            nearView = true;
            fetchArt(views[st.v].form.card, true);
            people.forEach((_, k) => fetchFace(portraitOf(k).card));
            prefetch(views[st.v].k);
        }

        // ---- Events ----
        artButton.addEventListener('click', event => openCard(views[st.shown].form.card, event));
        tabs.forEach(({ tab }) => tab.addEventListener('animationend', () => tab.classList.remove('is-changing')));

        // On a trail, a card named in a note (<span data-card="…">) walks to its stop, or opens
        // its popup if it isn't on the trail. Without script it stays plain text.
        if (trail && list) {
            list.querySelectorAll('[data-card]').forEach(link => {
                const target = people.findIndex(person => person.forms[0].card === link.dataset.card);
                link.classList.add('lore-trail-link');
                link.classList.toggle('is-stop', target >= 0);
                link.setAttribute('role', 'button');
                link.tabIndex = 0;
                link.setAttribute('aria-label', target >= 0
                    ? `${link.textContent}: go to stop ${target + 1}`
                    : `Show card: ${link.dataset.card}`);
                const follow = event => {
                    if (target >= 0) select(viewOf(target, 0), true);
                    else openCard(link.dataset.card, event);
                };
                link.addEventListener('click', follow);
                link.addEventListener('keydown', event => {
                    if (event.key !== 'Enter' && event.key !== ' ') return;
                    event.preventDefault();
                    follow(event);
                });
            });
        }
        strip.addEventListener('keydown', event => {
            if (event.key !== 'ArrowLeft' && event.key !== 'ArrowRight') return;
            const at = tabs.findIndex(({ tab }) => tab === document.activeElement);
            if (at < 0) return;
            event.preventDefault();
            const k = (at + (event.key === 'ArrowRight' ? 1 : -1) + people.length) % people.length;
            tabs[k].tab.focus();
            select(viewOf(k, picked[k]), true);
        });

        show(0);
        layout();
        if ('ResizeObserver' in window) new ResizeObserver(layout).observe(root);
        else window.addEventListener('resize', layout);
        if (document.fonts && document.fonts.ready) document.fonts.ready.then(fitNames);

        if ('IntersectionObserver' in window) {
            new IntersectionObserver(([entry]) => {
                st.visible = entry.isIntersecting;
                lastKey = '';
                if (!st.visible && st.next >= 0) {
                    st.v = st.next;
                    st.next = -1;
                    st.t = 0;
                    show(st.v);
                }
                if (st.visible) {
                    draw();
                    wake();
                }
            }).observe(canvas);
            const nearObserver = new IntersectionObserver(entries => {
                if (!entries.some(entry => entry.isIntersecting)) return;
                nearObserver.disconnect();
                comeNear();
            }, { rootMargin: '300px' });
            nearObserver.observe(root);
        } else {
            st.visible = true;
            comeNear();
            wake();
        }
    }

    function init() {
        document.querySelectorAll('[data-lore-reel]').forEach(root => {
            const data = window.LoreReelData && window.LoreReelData[root.dataset.loreReel];
            if (data && (data.kind === 'roster' || data.kind === 'trail')) renderRoster(root, data);
            else render(root);
        });
        if (document.querySelector('[data-lore-reel-ready]')) resumeMusic();
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', init);
    } else {
        init();
    }

    window.LoreReel = { init };
})();
