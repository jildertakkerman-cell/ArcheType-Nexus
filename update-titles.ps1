# Skip non-archetype pages
$skipPages = @(
    "Replay-Converter.html",
    "suggestion-form.html"
)

# Get all HTML files
$files = Get-ChildItem -Path $pagesDir -Filter "*.html"

foreach ($file in $files) {
    # Skip non-archetype pages
    if ($skipPages -contains $file.Name) {
        Write-Host "Skipping utility page: $($file.Name)" -ForegroundColor Yellow
        continue
    }
    
    # Extract archetype name from filename
    $baseName = $file.BaseName
    $archetypeName = $baseName -replace " Deck Analysis$", ""
    $archetypeName = $archetypeName -replace " Archetype Breakdown$", ""
    $archetypeName = $archetypeName -replace " Archetype Deep Dive$", ""
    $archetypeName = $archetypeName -replace " Deck Analyis$", ""  # typo in original
    $archetypeName = $archetypeName -replace " deck analysis$", ""
    $archetypeName = $archetypeName -replace " deck Analysis$", ""
    
    # Check if we have a custom title for this archetype
    $newTitle = $null
    foreach ($key in $titleMap.Keys) {
        if ($archetypeName -eq $key -or $archetypeName -ieq $key) {
            $newTitle = $titleMap[$key]
            break
        }
    }
    
    # If no custom title, create a generic one
    if (-not $newTitle) {
        $newTitle = "$archetypeName`: Archetype Analysis"
        Write-Host "No custom title for: $archetypeName - using generic" -ForegroundColor Cyan
    }
    
    # Read file content
    $content = Get-Content -Path $file.FullName -Raw -Encoding UTF8
    
    # Replace title using regex
    $pattern = '<title>.*?</title>'
    $replacement = "<title>$newTitle</title>"
    
    $newContent = $content -replace $pattern, $replacement
    
    # Write back to file
    Set-Content -Path $file.FullName -Value $newContent -Encoding UTF8 -NoNewline
    
    Write-Host "Updated: $($file.Name) -> $newTitle" -ForegroundColor Green
}

Write-Host "`nTitle update complete!" -ForegroundColor Magenta
