const START = '// __SYNERGY_URL_MAP_START__ (generated by scripts/generate-synergy-url-map.js — do not edit by hand)';
const END = '// __SYNERGY_URL_MAP_END__';

const root = path.join(__dirname, '..');
const pagesDir = path.join(root, 'pages');
const targetFile = path.join(root, 'assets', 'js', 'synergy-tags.js');

const pageFiles = fs.readdirSync(pagesDir).filter(f => f.toLowerCase().endsWith('.html'));
// Real-cased filenames, keyed lowercase, so wrong-cased aliases get fixed
// instead of silently 404ing on case-sensitive hosting.
const realCase = new Map(pageFiles.map(f => [f.toLowerCase(), f]));

const map = {};

for (const file of pageFiles) {
    const html = fs.readFileSync(path.join(pagesDir, file), 'utf8');
    const m = html.match(/initSynergyTags\(\s*(['"])((?:\\.|(?!\1).)*)\1/);
    if (!m) continue;
    const name = m[2].replace(/\\(.)/g, '$1');
    if (map[name] && map[name] !== file) {
        console.warn(`WARN: "${name}" is registered by both "${map[name]}" and "${file}" — keeping the first. Fix the page's initSynergyTags() call.`);
        continue;
    }
    map[name] = file;
}
const scannedCount = Object.keys(map).length;

for (const [name, file] of Object.entries(ALIASES)) {
    const real = realCase.get(file.toLowerCase());
    if (!real) {
        console.warn(`WARN: alias "${name}" points to missing page "${file}" — skipped.`);
        continue;
    }
    map[name] = real;
}

const sorted = Object.fromEntries(Object.entries(map).sort(([a], [b]) => a.localeCompare(b)));
const block = `${START}\nwindow._synergyUrlMap = ${JSON.stringify(sorted)};\n${END}`;

let src = fs.readFileSync(targetFile, 'utf8');
const re = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`);
if (re.test(src)) {
    src = src.replace(re, block);
} else if (/window\._synergyUrlMap\s*=\s*\{.*\};/s.test(src)) {
    src = src.replace(/window\._synergyUrlMap\s*=\s*\{.*\};/s, block);
} else {
    src = src.trimEnd() + '\n\n' + block + '\n';
}
fs.writeFileSync(targetFile, src);

console.log(`Wrote ${Object.keys(sorted).length} entries (${scannedCount} scanned from pages, ${Object.keys(sorted).length - scannedCount} via aliases) to ${path.relative(root, targetFile)}`);
